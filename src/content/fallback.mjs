let k = 0;
const key = () => `k${(++k).toString(36)}`;
/** sections: [{h?: string, p?: string | string[], list?: string[]}] -> Portable Text */
export function pt(sections) {
  const out = [];
  for (const s of sections) {
    if (s.h) out.push({ _type: 'block', _key: key(), style: 'h2', markDefs: [], children: [{ _type: 'span', _key: key(), text: s.h, marks: [] }] });
    for (const p of [].concat(s.p || [])) out.push({ _type: 'block', _key: key(), style: 'normal', markDefs: [], children: [{ _type: 'span', _key: key(), text: p, marks: [] }] });
    for (const li of s.list || []) out.push({ _type: 'block', _key: key(), style: 'normal', listItem: 'bullet', level: 1, markDefs: [], children: [{ _type: 'span', _key: key(), text: li, marks: [] }] });
  }
  return out;
}

